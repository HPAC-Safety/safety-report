#!/usr/bin/env node
// Opens, or updates, the one pull request that carries the French UI strings
// after a push to main (i18n-translate.yml; ADR-0021).
//
// A pull request opened with the built-in GITHUB_TOKEN does not trigger
// workflows — GitHub's loop protection — so CI would never report on it and the
// required checks would sit unfulfilled forever. TRANSLATION_PR_TOKEN is what
// makes CI run on the translation pull request: a fine-grained PAT scoped to
// THIS repository, with Contents and Pull requests both set to "Read and
// write", and nothing else. Never a classic PAT — its `repo` scope reaches
// every repository the user can see.
//
// Without it the pull request is still opened and is still correct; it just has
// to be nudged by hand (close and reopen it, or push an empty commit) before it
// can merge. That trade-off is recorded in ADR-0021, and the warning below is
// what tells whoever reads the run which happened.
//
// The branch is rebuilt from main on every run and force-pushed. It carries
// nothing a human wrote — every hand-written French string lives in
// locales/glossary.json, on main. `.fr-CA.pending` is a one-time sentinel for
// the initial generation; translate-locale.mjs deletes it once fr-CA.json
// exists, so later runs have nothing to add for it. One pull request that
// updates, rather than a new one every run.
//
// The token is never printed: a failed git command reports its own stderr.
//
// Environment: GH_TOKEN, USING_DEFAULT_TOKEN, SUMMARY, TRANSLATION_BRANCH,
// GITHUB_REPOSITORY; RUNNER_TEMP for the body file.
import { existsSync, mkdtempSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import path from 'node:path'

import { exec, isMain, required } from '../lib/actions.mjs'
import { BOT_EMAIL, BOT_NAME } from '../github/commit-to-pr-branch.mjs'

export const WARNING =
	'::warning::No TRANSLATION_PR_TOKEN is set, so this pull request is opened with the built-in GITHUB_TOKEN and CI will not run on it. Close and reopen it, or push an empty commit, before merging. See ADR-0021.'

export const PR_TITLE = 'Regenerate the French UI strings'

const BODY_TEXT = `Generated by \`.github/workflows/i18n-translate.yml\` from \`locales/en-CA.json\`.

**Read the French before merging.** Everything here is machine output except
keys stamped \`provider: "glossary"\`, which are HPAC's own wording copied
verbatim from \`locales/glossary.json\`.

Every generated key carries \`reviewed: false\` in \`locales/fr-CA.meta.json\`.
Flip it to \`true\` as you check each one — that flag is the record of what a
human has actually read, and nothing in the job ever sets it.

Do not hand-edit \`locales/fr-CA.json\` to fix a translation; the next run
regenerates it. Fix the English, or pin the term in \`locales/glossary.json\`.
A word that must always translate one way (\`upload\` → *téléverser*) goes in
\`locales/terms.json\` (ADR-0102): the translator is told it, and the i18n
check fails on French that breaks it.

See \`.spec/decisions/ADR-0021-ci-translation-opens-a-pull-request.md\`.
`

/** The pull request body: the run's summary, then the fixed reading instructions. */
export function prBody(summary) {
	return `${summary}.\n\n${BODY_TEXT}`
}

export function main({ env = process.env, exec: run = exec, log = console.log, cwd = process.cwd(), exists = existsSync } = {}) {
	const token = required(env, 'GH_TOKEN')
	const summary = env.SUMMARY ?? ''
	const branch = required(env, 'TRANSLATION_BRANCH')
	const repository = required(env, 'GITHUB_REPOSITORY')

	const step = (command, args, options = {}) => {
		const result = run(command, args, { cwd, ...options })
		if (result.status !== 0) throw new Error(`${command} ${args[0]} failed${result.stderr ? `: ${result.stderr}` : ''}`)
		return result
	}

	try {
		if (env.USING_DEFAULT_TOKEN === 'true') log(WARNING)

		step('git', ['config', 'user.name', BOT_NAME])
		step('git', ['config', 'user.email', BOT_EMAIL])
		step('git', ['remote', 'set-url', 'origin', `https://x-access-token:${token}@github.com/${repository}.git`])

		step('git', ['switch', '-C', branch])
		step('git', ['add', 'locales/fr-CA.json', 'locales/fr-CA.meta.json'])
		if (exists(path.join(cwd, 'locales/.fr-CA.pending'))) step('git', ['add', 'locales/.fr-CA.pending'])
		step('git', ['commit', '-m', PR_TITLE, '-m', `${summary}.`])
		step('git', ['push', '--force', 'origin', branch])

		const body = path.join(env.RUNNER_TEMP ?? mkdtempSync(path.join(tmpdir(), 'translation-pr-')), 'pr-body.md')
		writeFileSync(body, prBody(summary))

		const existing = run('gh', ['pr', 'view', branch, '--json', 'number', '--jq', '.number'], { cwd })
		if (existing.status === 0) {
			const edited = step('gh', ['pr', 'edit', branch, '--body-file', body])
			if (edited.stdout) log(edited.stdout)
			log('Updated the open translation pull request.')
		} else {
			const created = step('gh', ['pr', 'create', '--base', 'main', '--head', branch, '--title', PR_TITLE, '--body-file', body])
			if (created.stdout) log(created.stdout)
		}
	} catch (error) {
		log(`::error::${error.message}`)
		return 1
	}
	return 0
}

if (isMain(import.meta.url)) process.exit(main())
